/**
 * Bundle the connector into the Edge Function directory.
 *
 * Supabase deploys only what lives under supabase/functions, so the handler has to
 * be a file there rather than an import from this package. supabase-js is left
 * external and rewritten to an npm: specifier, which Deno resolves itself — no
 * point bundling a copy of it.
 */
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../../supabase/functions/mcp/handler.js');

await build({
  entryPoints: [resolve(here, '../src/http/handler.ts')],
  outfile: out,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  external: ['@supabase/supabase-js'],
  banner: {
    js: '// Generated by mcp/scripts/bundle.mjs — edit mcp/src/http, not this file.',
  },
});

const bundled = await readFile(out, 'utf8');
await writeFile(out, bundled.replace(
  /from\s*["']@supabase\/supabase-js["']/g,
  'from "npm:@supabase/supabase-js@2"',
));
console.log(`bundled -> ${out}`);
